// The Go engine is the reference oracle for the C++ port. This test (re)generates
// testvectors/vectors.json with `go test -run Vectors -update` and otherwise verifies the
// committed file still matches what the Go code produces, so the vectors cannot drift.
// The C++ port must reproduce every "expect" value from the "input" values.
var update = flag.Bool("update", false, "rewrite testvectors/vectors.json")

type vAEAD struct {
	Username   string            `json:"username"`
	Collection string            `json:"collection"`
	WireID     string            `json:"wire_id"`
	Epoch      int               `json:"epoch"`
	EpochKeys  map[string]string `json:"epoch_keys_hex"`
	NonceHex   string            `json:"nonce_hex"`
	Plaintext  string            `json:"plaintext_hex"`
	BlobHex    string            `json:"expect_blob_hex"` // nonce || ciphertext||tag, plaintext padded to 256
	CollKeyHex string            `json:"expect_collection_key_hex"`
}
type vID struct {
	Epoch0KeyHex string `json:"epoch0_key_hex"`
	Collection   string `json:"collection"`
	Logical      string `json:"logical_id"`
	Expect       string `json:"expect_wire_id"`
}
type vRecovery struct {
	KeyHex     string `json:"key_hex"`
	Expect     string `json:"expect_display"`
	SignPubHex string `json:"expect_sign_pub_hex"`
	BoxPubHex  string `json:"expect_box_pub_hex"`
}
type vIndex struct{ A, B, Expect string }
type vHLC struct {
	A, B   HLC
	Expect bool `json:"a_less_than_b"`
}
type vTree struct {
	Records []struct {
		ID string
		B  Bookmark
	} `json:"records"`
	Expect []string `json:"expect_flatten"`
}
type vHist struct {
	Local, Remote string
	Expect        string `json:"expect_merged"`
}
type vectors struct {
	Note     string      `json:"note"`
	AEAD     []vAEAD     `json:"aead"`
	IDs      []vID       `json:"record_ids"`
	Recovery []vRecovery `json:"recovery_keys"`
	Index    []vIndex    `json:"index_between"`
	HLC      []vHLC      `json:"hlc_order"`
	Tree     []vTree     `json:"bookmark_tree"`
	History  []vHist     `json:"history_merge"`
}

func seq(start byte, n int) []byte {
	b := make([]byte, n)
	for i := range b {
		b[i] = start + byte(i)
	}
	return b
}

func build(t *testing.T) vectors {
	v := vectors{Note: "Reference vectors generated by the Go engine (oracle). The C++ port must reproduce every expect_* value. Do not edit by hand; run: go test -run Vectors -update"}
	kb := &Keybag{Keys: map[int][]byte{0: seq(0x00, 32), 1: seq(0x40, 32)}}
	for _, c := range []struct {
		coll string
		ep   int
		pt   string
	}{{"bookmarks", 0, `{"v":1,"c":"bookmarks","id":"b1"}`}, {"passwords", 1, ""}, {"history", 1, string(bytes.Repeat([]byte("x"), 300))}} {
		nonce := seq(0x80, 24)
		wid := kb.RecordID(c.coll, "logical-1")
		blob, err := kb.sealNonce(nonce, "alice", c.coll, wid, c.ep, []byte(c.pt))
		if err != nil {
			t.Fatal(err)
		}
		ck, _ := kb.collectionKey(c.ep, c.coll)
		v.AEAD = append(v.AEAD, vAEAD{"alice", c.coll, wid, c.ep, map[string]string{"0": hex.EncodeToString(kb.Keys[0]), "1": hex.EncodeToString(kb.Keys[1])},
			hex.EncodeToString(nonce), hex.EncodeToString([]byte(c.pt)), hex.EncodeToString(blob), hex.EncodeToString(ck)})
		if pt, err := kb.open("alice", c.coll, wid, c.ep, blob); err != nil || string(pt) != c.pt {
			t.Fatalf("self-check failed: %v", err)
		}
	}
	for _, l := range []string{"logical-1", "https://example.org/", ""} {
		v.IDs = append(v.IDs, vID{hex.EncodeToString(kb.Keys[0]), "bookmarks", l, kb.RecordID("bookmarks", l)})
	}
	var rk RecoveryKey
	copy(rk[:], seq(0x10, 32))
	d := rk.derive()
	v.Recovery = append(v.Recovery, vRecovery{hex.EncodeToString(rk[:]), rk.String(), hex.EncodeToString(d.signPub), hex.EncodeToString(d.boxPub)})
	for _, p := range [][2]string{{"", ""}, {"a", "b"}, {"a", "a1"}, {"az", "b"}, {"a", ""}, {"", "a"}, {"a0z", "a1"}, {"zzz", ""}} {
		v.Index = append(v.Index, vIndex{p[0], p[1], IndexBetween(p[0], p[1])})
	}
	for _, p := range [][2]HLC{{{1, 0, "a"}, {1, 0, "b"}}, {{1, 5, "z"}, {2, 0, "a"}}, {{2, 1, "a"}, {2, 0, "z"}}, {{3, 3, "a"}, {3, 3, "a"}}} {
		v.HLC = append(v.HLC, vHLC{p[0], p[1], p[0].Less(p[1])})
	}
	// bookmark tree incl. orphan, cycle, folder-with-children
	eng, err := NewEngine(&Account{St: &DeviceState{DeviceID: "d", Keybag: kb}}, &MemLocalStore{}, nil)
	if err != nil {
		t.Fatal(err)
	}
	recs := []struct {
		ID string
		B  Bookmark
	}{
		{"F1", Bookmark{Kind: "folder", Title: "F1", Parent: "F2", Index: "a"}},
		{"F2", Bookmark{Kind: "folder", Title: "F2", Parent: "F1", Index: "a"}},
		{"B1", Bookmark{Kind: "url", Title: "one", URL: "https://1", Parent: "toolbar", Index: "b"}},
		{"B2", Bookmark{Kind: "url", Title: "two", URL: "https://2", Parent: "toolbar", Index: "a"}},
		{"B3", Bookmark{Kind: "url", Title: "orphan", URL: "https://3", Parent: "missing", Index: "a"}},
		{"B4", Bookmark{Kind: "url", Title: "tie-b", URL: "https://4", Parent: "other", Index: "m"}},
		{"B5", Bookmark{Kind: "url", Title: "tie-a", URL: "https://5", Parent: "other", Index: "m"}},
	}
	for _, r := range recs {
		_ = eng.PutBookmark(r.ID, r.B)
	}
	v.Tree = append(v.Tree, vTree{Records: recs, Expect: eng.BookmarkTree().Flatten("")})
	for _, p := range [][2]string{
		{`{"url":"u","title":"A","visits":[1,3]}`, `{"url":"u","title":"B","visits":[2,3]}`},
		{`{"url":"u","title":"A","visits":[1]}`, `{"url":"u","title":"B","visits":[1]}`},
	} {
		v.History = append(v.History, vHist{p[0], p[1], string(mergeHistory([]byte(p[0]), []byte(p[1])))})
	}
	return v
}

func TestVectors(t *testing.T) {
	got, _ := json.MarshalIndent(build(t), "", "  ")
	got = append(got, '\n')
	const path = "testvectors/vectors.json"
	if *update {
		_ = os.MkdirAll("testvectors", 0o755)
		if err := os.WriteFile(path, got, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("%v (run with -update)", err)
	}
	if !bytes.Equal(got, want) {
		t.Fatal("testvectors/vectors.json is stale or Go behaviour changed; review and run: go test -run Vectors -update")
	}
}
