#!/usr/bin/env python3
# Embeds every file under <dist> into a C++ table: kCorvidWebuiFiles[] = {"page/file", data, size}.
# Usage: embed_resources.py <dist> <out.cc> <depfile>
import os
import sys


def main() -> int:
    dist, out, depfile = sys.argv[1:4]
    files = []
    for d, _, names in os.walk(dist):
        for n in names:
            p = os.path.join(d, n)
            files.append((os.path.relpath(p, dist).replace(os.sep, '/'), p))
    files.sort()
    with open(out, 'w') as f:
        f.write('// Generated by embed_resources.py. Do not edit.\n#include "corvid/webui/corvid_resources.h"\n\nnamespace corvid {\nnamespace {\n')
        for i, (_, p) in enumerate(files):
            data = open(p, 'rb').read()
            f.write(f'constexpr uint8_t kData{i}[] = {{{",".join(str(b) for b in data)}{"" if data else "0"}}};\n')
        f.write('\nconst EmbeddedFile kFiles[] = {\n')
        for i, (rel, p) in enumerate(files):
            f.write(f'    {{"{rel}", kData{i}, {os.path.getsize(p)}}},\n')
        f.write('};\n}  // namespace\n\nbase::span<const EmbeddedFile> CorvidWebuiFiles() { return kFiles; }\n}  // namespace corvid\n')
    with open(depfile, 'w') as f:
        f.write(out + ': ' + ' '.join(p for _, p in files) + '\n')
    return 0


if __name__ == '__main__':
    sys.exit(main())
