// Builds the pages into dist/ (or the tests into dist-test/ with --tests).
//   dist/shared/{tokens,theme-default,base}.css
//   dist/<page>/{index.html,<page>.js,<page>.css}
//   dist/index.html   (dev index of all pages and error samples)

import * as esbuild from 'esbuild';
import { cpSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(root, 'src');
export const PAGES = ['newtab', 'settings', 'error'];

/** The product name lives in build/branding.conf only. */
export function productName() {
  try {
    const conf = readFileSync(join(root, '..', 'build', 'branding.conf'), 'utf8');
    const m = /^PRODUCT_NAME="([^"]+)"/m.exec(conf);
    if (m) return m[1];
  } catch {}
  throw new Error('PRODUCT_NAME not found in ../build/branding.conf');
}

const define = { __PRODUCT_NAME__: JSON.stringify(productName()) };
const HEADER = '/* SPDX-License-Identifier: GPL-3.0-or-later\n * Generated by webui/scripts/build.mjs. Do not edit. */\n';

async function loadModule(code) {
  const out = await esbuild.build({
    stdin: { contents: code, resolveDir: root, loader: 'ts' },
    bundle: true, format: 'esm', platform: 'node', write: false, define,
  });
  return import('data:text/javascript;base64,' + Buffer.from(out.outputFiles[0].text).toString('base64'));
}

async function buildPages(outDir) {
  rmSync(outDir, { recursive: true, force: true });
  mkdirSync(join(outDir, 'shared'), { recursive: true });

  const m = await loadModule(`
    export { tokensCss } from './src/tokens/tokens.ts';
    export { themeCss } from './src/shared/theme.ts';
    export { DEFAULT_PREFS } from './src/shared/prefs.ts';
    export { SAMPLES } from './src/pages/error/samples.ts';`);
  writeFileSync(join(outDir, 'shared', 'tokens.css'), HEADER + m.tokensCss());
  // First paint before JS runs: the default theme, following the system mode.
  writeFileSync(join(outDir, 'shared', 'theme-default.css'), HEADER + m.themeCss(m.DEFAULT_PREFS).css + '\n');
  cpSync(join(src, 'styles', 'base.css'), join(outDir, 'shared', 'base.css'));

  await esbuild.build({
    entryPoints: PAGES.map((p) => ({ in: join(src, 'pages', p, `${p}.ts`), out: join(p, p) })),
    outdir: outDir, bundle: true, format: 'esm', target: 'chrome120',
    minify: process.argv.includes('--minify'), sourcemap: true, define,
    legalComments: 'eof', logLevel: 'warning',
  });
  for (const p of PAGES) {
    for (const f of readdirSync(join(src, 'pages', p))) {
      if (f.endsWith('.html') || f.endsWith('.css')) cpSync(join(src, 'pages', p, f), join(outDir, p, f));
    }
  }

  const links = [
    '<li><a href="newtab/">New tab</a></li>',
    '<li><a href="settings/">Settings</a></li>',
    ...Object.keys(m.SAMPLES).map((s) => `<li><a href="error/?sample=${s}">Error: ${s}</a></li>`),
    '<li><a href="error/?code=ERR_CONNECTION_RESET&amp;url=https://example.org/">Error from query: ERR_CONNECTION_RESET</a></li>',
  ];
  writeFileSync(join(outDir, 'index.html'), `<!doctype html>
<meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>${productName()} pages (dev)</title><link rel="icon" href="data:,">
<link rel="stylesheet" href="shared/tokens.css"><link rel="stylesheet" href="shared/theme-default.css"><link rel="stylesheet" href="shared/base.css">
<main class="card" id="dev-index"><h1 class="headline-medium">${productName()} pages</h1><ul>${links.join('')}</ul></main>
`);
}

/**
 * Files for the browser (build/webui-sync.sh copies them into the Chromium
 * tree, where components/corvid_webui packs them):
 *   shared/*.css, <page>/{index.html,<page>.js,<page>.css}   WebUI pages
 *   error/error.html   one self-contained file: the error pages commit in an
 *                      opaque origin and cannot load other files
 * Minified, no source maps. Page HTML loads corvid-init.js (served by the
 * browser: prefs and accent colour) before the page script.
 */
async function buildChromium(outDir) {
  const tmp = join(root, 'dist-chromium-tmp');
  rmSync(tmp, { recursive: true, force: true });
  rmSync(outDir, { recursive: true, force: true });
  await buildPages(tmp);
  await esbuild.build({
    entryPoints: PAGES.map((p) => ({ in: join(src, 'pages', p, `${p}.ts`), out: join(p, p) })),
    outdir: tmp, bundle: true, format: 'esm', target: 'chrome120', minify: true, sourcemap: false,
    define, legalComments: 'eof', logLevel: 'warning', allowOverwrite: true,
  });
  mkdirSync(join(outDir, 'shared'), { recursive: true });
  for (const f of readdirSync(join(tmp, 'shared'))) cpSync(join(tmp, 'shared', f), join(outDir, 'shared', f));
  for (const p of PAGES) {
    const html = readFileSync(join(tmp, p, 'index.html'), 'utf8');
    mkdirSync(join(outDir, p), { recursive: true });
    if (p === 'error') {
      const inlined = html
        .replace(/<link rel="stylesheet" href="([^"]+)">/g, (_, href) =>
          `<style>${readFileSync(join(tmp, p, href), 'utf8').replace(/<\/style/gi, '<\\/style')}</style>`)
        .replace(/<script type="module" src="([^"]+)"><\/script>/, (_, s) =>
          `<script type="module">${readFileSync(join(tmp, p, s), 'utf8').replace(/<\/script/gi, '<\\/script')}</script>`);
      if (/<link rel="stylesheet"|<script[^>]+src=/.test(inlined)) throw new Error('error page still loads other files');
      writeFileSync(join(outDir, p, 'error.html'), inlined);
      continue;
    }
    const page = html
      .replaceAll('href="../shared/', 'href="shared/')
      .replace('<script type="module"', '<script src="corvid-init.js"></script>\n  <script type="module"');
    if (!page.includes('corvid-init.js')) throw new Error(`${p}: no module script found`);
    writeFileSync(join(outDir, p, 'index.html'), page);
    cpSync(join(tmp, p, `${p}.js`), join(outDir, p, `${p}.js`));
    cpSync(join(tmp, p, `${p}.css`), join(outDir, p, `${p}.css`));
  }
  rmSync(tmp, { recursive: true, force: true });
}

async function buildTests(outDir) {
  rmSync(outDir, { recursive: true, force: true });
  const tests = readdirSync(join(root, 'test')).filter((f) => f.endsWith('.test.ts'));
  await esbuild.build({
    entryPoints: tests.map((f) => ({ in: join(root, 'test', f), out: f.replace(/\.ts$/, '') })),
    outdir: outDir, outExtension: { '.js': '.mjs' }, bundle: true, format: 'esm', platform: 'node',
    define, logLevel: 'warning',
  });
}

export async function build() {
  await buildPages(join(root, 'dist'));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const ci = process.argv.indexOf('--chromium');
  if (process.argv.includes('--tests')) await buildTests(join(root, 'dist-test'));
  else if (ci > 0) {
    const out = process.argv[ci + 1];
    if (!out) throw new Error('--chromium needs an output folder');
    await buildChromium(out);
    console.log(`built ${out}`);
  } else {
    await build();
    console.log('built dist/');
  }
}
