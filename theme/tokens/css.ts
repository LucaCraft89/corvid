// Token generation: roles + static tokens -> flat { "--cv-*": value } map and CSS text.
import { generateRoles, ROLE_NAMES, type SchemeOptions } from '../engine/scheme.ts';
import {
  ELEVATION_SHADOW, FONT_FAMILY, MOTION_CSS, MOTION_SPRINGS, SHAPE_DP,
  STATE_LAYER_OPACITY, TYPE_BASELINE, TYPE_EMPHASIZED, springToLinear, type TypeStyle,
} from './static.ts';

export type TokenMap = Record<string, string>;

export function kebab(s: string): string {
  return s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
}

export function colorTokens(opts: SchemeOptions): TokenMap {
  const roles = generateRoles(opts);
  const out: TokenMap = {};
  for (const name of ROLE_NAMES) out[`--cv-color-${kebab(name)}`] = roles[name];
  out['--cv-color-scheme'] = opts.mode;
  return out;
}

/** Tokens that do not depend on the seed. Computed once. */
export function staticTokens(): TokenMap {
  const out: TokenMap = {};
  for (const [k, dp] of Object.entries(SHAPE_DP)) out[`--cv-shape-${k}`] = dp >= 9999 ? '9999px' : `${dp / 16}rem`;
  for (const [k, s] of Object.entries(MOTION_SPRINGS)) {
    out[`--cv-motion-${k}-damping`] = String(s.damping);
    out[`--cv-motion-${k}-stiffness`] = String(s.stiffness);
    out[`--cv-motion-${k}-easing`] = springToLinear(s, k.startsWith('slow') ? 900 : k.startsWith('fast') ? 350 : 600);
  }
  for (const [k, v] of Object.entries(MOTION_CSS)) out[`--cv-motion-${k}`] = v;
  for (const [k, v] of Object.entries(ELEVATION_SHADOW)) out[`--cv-elevation-${k}`] = v;
  for (const [k, v] of Object.entries(STATE_LAYER_OPACITY)) out[`--cv-state-${k}`] = String(v);
  for (const [k, v] of Object.entries(FONT_FAMILY)) out[`--cv-font-${k}`] = v;
  const type = (prefix: string, styles: Record<string, TypeStyle>) => {
    for (const [k, s] of Object.entries(styles)) {
      out[`--cv-type-${prefix}${k}-size`] = `${s.size / 16}rem`;
      out[`--cv-type-${prefix}${k}-line`] = `${s.line / 16}rem`;
      out[`--cv-type-${prefix}${k}-weight`] = String(s.weight);
      out[`--cv-type-${prefix}${k}-tracking`] = `${s.tracking / 16}rem`;
    }
  };
  type('', TYPE_BASELINE);
  type('emphasized-', TYPE_EMPHASIZED);
  return out;
}

export function allTokens(opts: SchemeOptions): TokenMap {
  return { ...colorTokens(opts), ...staticTokens() };
}

export function tokensToCss(tokens: TokenMap, selector = ':root'): string {
  const body = Object.entries(tokens).map(([k, v]) => `  ${k}: ${v};`).join('\n');
  return `${selector} {\n${body}\n}\n`;
}

/** Default stylesheet: light + dark variants for the default seed, switched by prefers-color-scheme / data-theme. */
export function defaultStylesheet(seed: string): string {
  const light = allTokens({ seed, mode: 'light' });
  const dark = colorTokens({ seed, mode: 'dark' });
  return [
    '/* GENERATED by theme/tokens/generate.ts. Do not edit. */',
    tokensToCss(light, ':root'),
    `@media (prefers-color-scheme: dark) {\n${tokensToCss(dark, '  :root:not([data-theme="light"])')}}\n`,
    tokensToCss(dark, ':root[data-theme="dark"]'),
  ].join('\n');
}
