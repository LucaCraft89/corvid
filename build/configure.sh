# Write out/Default/args.gn and run gn gen. Starts from Helium's flags.gn +
# flags.linux.gn, drops the keys we override, then adds dev-VM args:
# component build, symbol_level=0, no LTO, no PGO, ccache, plain ninja.
set -euo pipefail
. "$(dirname "${BASH_SOURCE[0]}")/config.sh"
[ -f "$SRC/.resources.stamp" ] || { echo "run build/patch.sh first" >&2; exit 1; }

overrides=(is_official_build is_component_build is_debug symbol_level blink_symbol_level
           use_thin_lto is_cfi chrome_pgo_phase cc_wrapper use_siso use_sysroot
           target_cpu v8_target_cpu)
pattern="^[[:space:]]*($(IFS='|'; echo "${overrides[*]}"))[[:space:]]*="

mkdir -p "$OUT"
{
    echo "# Generated by corvid build/configure.sh. Do not edit; edit the script."
    echo "# From helium-chromium/flags.gn + helium-linux/flags.linux.gn:"
    cat "$HELIUM_MAIN/flags.gn" "$HELIUM_LINUX/flags.linux.gn" | grep -Ev "$pattern"
    cat <<ARGS
# Corvid dev-VM overrides:
is_official_build = false
is_component_build = true
is_debug = false
symbol_level = 0
blink_symbol_level = 0
use_thin_lto = false
is_cfi = false
chrome_pgo_phase = 0
use_sysroot = true
use_siso = false
cc_wrapper = "ccache"
target_cpu = "$ARCH"
v8_target_cpu = "$ARCH"
ARGS
} > "$OUT/args.gn"
cat "$OUT/args.gn"

cd "$SRC"
./buildtools/linux64/gn gen out/Default --fail-on-unused-args
