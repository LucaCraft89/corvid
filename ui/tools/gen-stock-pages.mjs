// Generates (from ui/pages/stock-pages.json) the table section of docs/stock-pages.md and the C++ lookup
// table src-overlay/corvid/webui/stock_page_table.inc. Usage: node ui/tools/gen-stock-pages.mjs [--check]
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../../', import.meta.url));
const data = JSON.parse(readFileSync(root + 'ui/pages/stock-pages.json', 'utf8'));
const pages = [...data.pages].sort((a, b) => a.host.localeCompare(b.host));

const md = [
  '<!-- BEGIN GENERATED (ui/tools/gen-stock-pages.mjs) -->',
  '| chrome:// host | Status | Corvid target | Note |',
  '|---|---|---|---|',
  ...pages.map((p) => `| \`${p.host}\` | ${p.action} | ${p.target === 'blocked' ? '`corvid://blocked`' : `\`corvid://${p.target}\``} | ${p.note || ''} |`),
  '<!-- END GENERATED -->',
].join('\n');

const inc = [
  '// GENERATED by ui/tools/gen-stock-pages.mjs from ui/pages/stock-pages.json. UNVERIFIED (not compiled).',
  '// {host, action, target}. action: 0 replaced, 1 redirected, 2 blocked.',
  ...pages.map((p) => `{"${p.host}", ${p.action === 'replaced' ? 0 : p.action === 'redirected' ? 1 : 2}, "${p.target}"},`),
  '',
].join('\n');

const docPath = root + 'docs/stock-pages.md';
const incPath = root + 'src-overlay/corvid/webui/stock_page_table.inc';
let doc = existsSync(docPath) ? readFileSync(docPath, 'utf8') : '';
if (!doc.includes('<!-- BEGIN GENERATED')) throw new Error('docs/stock-pages.md is missing the BEGIN/END GENERATED markers');
doc = doc.replace(/<!-- BEGIN GENERATED[\s\S]*<!-- END GENERATED -->/, md);

if (process.argv.includes('--check')) {
  const stale = readFileSync(docPath, 'utf8') !== doc || !existsSync(incPath) || readFileSync(incPath, 'utf8') !== inc;
  if (stale) { console.error('stock page outputs are stale; run: node ui/tools/gen-stock-pages.mjs'); process.exit(1); }
  console.log('stock page outputs up to date');
} else {
  writeFileSync(docPath, doc);
  writeFileSync(incPath, inc);
  console.log(`wrote ${pages.length} entries`);
}
